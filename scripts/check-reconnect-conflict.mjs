import assert from "node:assert/strict";
import { loadState, resolvePlanningLoad, saveState } from "../src/modules/storage.js";
const memory = new Map();
globalThis.localStorage = { getItem: key => memory.get(key) || null, setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) };
const local = { beneficiaryId: "test", auxiliaries: [], overrides: { "2026-8-1-morning": "a" }, updatedAt: "2026-09-01T00:00:00Z" };
const cloud = { ...local, overrides: { "2026-8-1-morning": "b", "2026-8-2-morning": "b" }, updatedAt: "2026-09-24T00:00:00Z" };
assert.deepEqual(resolvePlanningLoad(local, cloud), { state: local, conflict: true });
assert.equal(resolvePlanningLoad(local, { ...local, updatedAt: cloud.updatedAt }).conflict, false);
assert.equal(resolvePlanningLoad({ ...local, overrides: {} }, cloud).state.overrides["2026-8-1-morning"], undefined);
assert.equal(resolvePlanningLoad({ ...local, beneficiaryId: "other" }, cloud).state, cloud);
memory.set("planning-avd-state-v2", JSON.stringify(local));
let writes = 0;
let race = false;
const snapshot = value => ({ exists: true, data: () => ({ value }) });
const ref = { collection() { return this; }, doc() { return this; }, async get() { return snapshot(cloud); }, async set() { writes++; } };
const db = { collection() { return ref; }, async runTransaction(callback) { return callback({ get: async () => snapshot(race ? { ...cloud, updatedAt: "changed" } : cloud), set() { writes++; } }); } };
const saved = await loadState({ db, user: { uid: "admin" } });
assert.equal(saved.__cloud.conflict, true);
assert.equal(saved.__cloud.ready, false);
assert.deepEqual(saved.overrides, local.overrides, "Migration must preserve assignments");
assert.equal(writes, 0);
assert.ok([...memory.keys()].some(key => key.includes("recovery")));
race = true;
const result = await saveState({ db, user: { uid: "admin" }, state: local, expectedUpdatedAt: cloud.updatedAt, expectedBeneficiaryUpdatedAt: cloud.updatedAt });
assert.equal(result.reason, "conflict");
assert.equal(writes, 0, "Concurrent cloud update must not be overwritten");
console.log("Reconnexion : local conserve, choix obligatoire, migration et concurrence OK");
