import assert from "node:assert/strict";
import { copyMonthWithinQuotas } from "../src/modules/month-template.js";
import { applyManualAssignments, buildEmptySchedule } from "../src/modules/manual-schedule.js";
import { calculateAssignedHours } from "../src/modules/hour-accounting.js";
import { monthContextCells } from "../src/modules/dates.js";
const overrides = {};
for (let day = 1; day <= 31; day++) overrides[`2026-9-${day}-morning`] = { workers: ["A", "B"], notPerformed: ["A"] };
const auxiliaries = [{ id: "A", quota: 12.5 }, { id: "B", quota: 0 }];
const args = { year: 2026, month: 10, overrides, hourOverrides: {}, auxiliaries };
const filled = copyMonthWithinQuotas(args);
const schedule = applyManualAssignments({ ...args, assignments: filled.overrides, hourOverrides: filled.hourOverrides, schedule: buildEmptySchedule(args) });
const hours = calculateAssignedHours(schedule, auxiliaries);
assert.equal(hours.A.total, 12.5);
assert.equal(hours.B.total, 0);
assert.equal(schedule[3].morning.workerHours.A, 2.5);
assert.deepEqual(schedule[1].morning.notPerformed, []);
assert.deepEqual(filled.overrides['2026-9-1-morning'], overrides['2026-9-1-morning']);
assert.equal(schedule[4].morning.worker, "");
assert.equal(overrides['2026-10-1-morning'], undefined);
assert.ok(monthContextCells(2026, 11, true).some(cell => cell.year === 2027 && cell.month === 0));
assert.ok(monthContextCells(2026, 4, true).some(cell => cell.month === 5));
const feb = copyMonthWithinQuotas({ ...args, year: 2027, month: 1 });
assert.equal(feb.count, 0);
console.log("Copie plafonnee : dernier creneau reduit, quotas individuels, absence non recopiee et changement d'annee OK");
