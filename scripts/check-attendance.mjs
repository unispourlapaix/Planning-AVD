import assert from "node:assert/strict";
import { setNotPerformed } from "../src/modules/attendance.js";
import { buildEmptySchedule, applyManualAssignments, copyPreviousMonthAssignments } from "../src/modules/manual-schedule.js";
import { calculatePerformedHours, calculateAssignedHours } from "../src/modules/hour-accounting.js";
const params = { year: 2026, month: 8, day: 1 };
const original = { "2026-8-1-morning": ["A", "B"], "2026-8-1-afternoon": "A" };
let assignments = setNotPerformed({ ...params, assignments: original, worker: "A", shift: "morning", absent: true });
const aux = [{ id: "A", quota: 151 }, { id: "B", quota: 71 }];
const schedule = () => applyManualAssignments({ ...params, schedule: buildEmptySchedule(params), assignments });
const count = () => calculatePerformedHours(schedule(), aux, { ...params, now: new Date(2026, 9, 2) });
assert.equal(count().A.total, 5);
assert.equal(count().A.absentHours, 5);
assert.equal(count().B.total, 5);
assert.equal(calculateAssignedHours(schedule(), aux).A.total, 10);
assignments = setNotPerformed({ ...params, assignments, worker: "A", absent: true });
assert.equal(count().A.total, 0);
assert.equal(count().A.absentSlots, 2);
assignments = JSON.parse(JSON.stringify(assignments));
assert.equal(count().A.absentHours, 10);
assignments = setNotPerformed({ ...params, assignments, worker: "A", absent: false });
assert.equal(count().A.total, 10);
assert.deepEqual(original["2026-8-1-morning"], ["A", "B"]);
console.log("Absences : creneau, journee, renfort, sauvegarde et annulation OK");
