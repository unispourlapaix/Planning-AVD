import assert from "node:assert/strict";
import { buildEmptySchedule, applyManualAssignments } from "../src/modules/manual-schedule.js";
import { calculateAssignedHours, summarizeHours } from "../src/modules/hour-accounting.js";
import { buildPersonalPlanningEmail } from "../src/modules/personal-planning-email.js";
import { buildPersonalSharePayloads } from "../src/modules/storage.js";
const auxiliaries = [{ id: "A", name: "Alice", email: "a@example.test", quota: 151 }, { id: "B", name: "Benoit", email: "b@example.test", quota: 151 }];
const params = { year: 2026, month: 8 };
const schedule = applyManualAssignments({ ...params, schedule: buildEmptySchedule(params), assignments: { "2026-8-1-bedtime": "A", "2026-8-1-night": "B" }, hourOverrides: {} });
assert.equal(schedule[1].bedtime.hours, 2);
assert.equal(schedule[1].night.hours, 12);
assert.equal(schedule[2].morning.worker, "");
const accounts = calculateAssignedHours(schedule, auxiliaries);
assert.equal(accounts.A.total, 2);
assert.equal(accounts.B.total, 12);
assert.equal(summarizeHours(accounts.A).bedtime, 2);
const mail = buildPersonalPlanningEmail({ ...params, schedule, auxiliaries, auxiliary: auxiliaries[0] });
assert.equal(mail.rows[0].range, "20:00–22:00");
const nightMail = buildPersonalPlanningEmail({ ...params, schedule, auxiliaries, auxiliary: auxiliaries[1] });
assert.equal(nightMail.rows[0].range, "20:30–08:30 (+1 j)");
const payloads = buildPersonalSharePayloads({ ...params, schedule, auxiliaries, beneficiaryId: "test" });
assert.ok(JSON.stringify(payloads).includes("bedtime"));
const edited = applyManualAssignments({ ...params, schedule: buildEmptySchedule(params), assignments: { "2026-8-1-bedtime": "A", "2026-8-1-night": "B" }, hourOverrides: { "2026-8-1-bedtime::A": 1.5 } });
assert.equal(calculateAssignedHours(edited, auxiliaries).A.total, 1.5);
assert.equal(calculateAssignedHours(edited, auxiliaries).B.total, 12);
console.log("Four shifts OK: independent workers, editable durations, accounting, sharing and email timing.");
